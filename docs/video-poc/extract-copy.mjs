// Reads the DE/TR copy from index.html and writes copy.js for the video PoC.
// The video reads the same i18n keys as the site, so a copy change on the site
// only needs this script to run again (no edits inside the video).
// Usage: node docs/video-poc/extract-copy.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../../', import.meta.url);
const html = readFileSync(new URL('index.html', root), 'utf8');

const start = html.indexOf('var translations = ');
const end = html.indexOf('  // German is the base language');
if (start < 0 || end < 0) throw new Error('translations block not found in index.html');

const literal = html.slice(start + 'var translations = '.length, end).trim().replace(/;$/, '');
const translations = new Function(`return (${literal});`)();

const out = `// Generated by docs/video-poc/extract-copy.mjs from index.html. Do not edit by hand.\nwindow.WW_COPY = ${JSON.stringify(translations, null, 2)};\n`;
writeFileSync(new URL('docs/video-poc/copy.js', root), out, 'utf8');
console.log(`copy.js written: ${Object.keys(translations.de).length} DE keys, ${Object.keys(translations.tr).length} TR keys`);
