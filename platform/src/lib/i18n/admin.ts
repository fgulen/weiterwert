export type AdminTexte = typeof DE;

const SAMMLUNG: Record<Lang, AdminTexte> = { de: DE, tr: TR, en: DE };

/** The admin texts for one language. English is not translated yet and shows German. */
export function adminTexte(lang: Lang): AdminTexte {
  return SAMMLUNG[lang] ?? DE;
}

/** Fills {placeholders}. Unknown placeholders stay as they are. */
export function mit(text: string, werte: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (_, k: string) => String(werte[k] ?? `{${k}}`));
}
